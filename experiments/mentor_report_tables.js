/* Make every table in the report comparable: bars, sorting, facet filters.

   The report's tables are generated by one `tbl()` helper, so rather than
   touch the content code this walks the finished DOM.  Three problems it
   fixes, in the order they were raised:

   - a setting like "full-generic" spans several rows (one per seat, or per
     round), so reading one setting across rounds means scanning past
     everything else.  The facet chips isolate it; the group button pulls the
     rows that share a setting next to each other.
   - magnitudes were text only.  Numeric cells get a bar scaled to the largest
     absolute value in their own column, so columns stay comparable within
     themselves and are never compared across units.
   - no way to reorder.  Headers sort, and a third click restores the
     authored order, which carries meaning in several tables.

   Cells holding a transition ("30.0% → 20.0%") are deliberately left without
   a bar: one bar cannot honestly stand for two numbers. */
(function () {
  const NUM = /^\s*([+-]?[\d,]+(?:\.\d+)?)\s*(%|pp)?\s*$/;
  const SPLIT = /[\/·,、\s]+/;

  const parse = (txt) => {
    if (txt.includes("→") || txt.includes("±")) return null;
    const m = NUM.exec(txt.replace(/,/g, ""));
    return m ? parseFloat(m[1]) : null;
  };

  // Column labels that have a formal definition in the definitions section.
  // Built from that section's own first column, so the two can never drift:
  // a definition that is renamed stops matching instead of pointing nowhere.
  const glossary = new Map();
  const defSection = document.getElementById("definitions");
  if (defSection) {
    defSection.querySelectorAll("tbody tr").forEach((tr, i) => {
      const term = tr.cells[0] && tr.cells[0].textContent.trim();
      const body = [...tr.cells].slice(1, -1).map((c) => c.textContent.trim())
        .filter(Boolean).join(" ／ ");
      if (!term) return;
      tr.id = tr.id || "def-" + i;
      glossary.set(term, {id: tr.id, text: body});
      // a label like "等价 / 弱化 / 细化（格子表）" also answers to its parts
      term.replace(/（.*?）/g, "").split(/\s*\/\s*/).forEach((alias) => {
        const a = alias.trim();
        if (a && a !== term && !glossary.has(a)) glossary.set(a, {id: tr.id, text: body});
      });
    });
  }

  const linkHeader = (th) => {
    const label = th.textContent.trim();
    const hit = glossary.get(label);
    if (!hit) return;
    th.classList.add("ft-def");
    th.title = hit.text;
    th.dataset.def = hit.id;
  };

  const build = (table) => {
    const head = [...table.tHead.rows[0].cells].map((c) => c.textContent.trim());
    const body = table.tBodies[0];
    const rows = [...body.rows];
    if (rows.length < 3) return;
    rows.forEach((r, i) => (r.dataset.ftOrder = i));

    // which columns are numeric enough to deserve a bar
    const nCols = head.length;
    const vals = [];
    for (let c = 0; c < nCols; c++) {
      const col = rows.map((r) => (r.cells[c] ? parse(r.cells[c].textContent) : null));
      const ok = col.filter((v) => v !== null).length;
      vals.push(ok >= Math.max(2, rows.length * 0.6) ? col : null);
    }

    // A fixed-width track next to the number, not a fill across the cell: a
    // cell-wide bar runs under the neighbouring column's digits, and several
    // wide bars in a row merge into one grey band that reads as nothing.
    for (let c = 0; c < nCols; c++) {
      if (!vals[c]) continue;
      const present = vals[c].filter((v) => v !== null);
      const max = Math.max(...present.map(Math.abs)) || 1;
      const signed = present.some((v) => v < 0) && present.some((v) => v > 0);
      rows.forEach((r, i) => {
        const v = vals[c][i];
        const cell = r.cells[c];
        if (v === null || !cell) return;
        cell.classList.add("ft-num");
        const w = (Math.abs(v) / max) * (signed ? 50 : 100);
        // A signed column keeps zero on the track's midpoint so the sign is
        // visible as a direction, not only as a minus glyph.
        const style = signed
          ? `width:${w.toFixed(1)}%;left:${(v < 0 ? 50 - w : 50).toFixed(1)}%`
          : `width:${w.toFixed(1)}%;left:0`;
        cell.innerHTML =
          `<i class="ft-track${signed ? " ft-signed" : ""}">` +
          `<i class="ft-fill${v < 0 ? " ft-neg" : ""}" style="${style}"></i></i>` +
          `<b>${cell.textContent.trim()}</b>`;
      });
    }

    // label columns: the ones that are not numeric
    const labelCols = [];
    for (let c = 0; c < nCols; c++) if (!vals[c]) labelCols.push(c);

    // sorting
    [...table.tHead.rows[0].cells].forEach((th, c) => {
      th.classList.add("ft-th");
      if (vals[c]) th.classList.add("ft-th-num");
      linkHeader(th);
      th.tabIndex = 0;
      let state = 0;
      const go = () => {
        state = (state + 1) % 3;
        table.tHead.rows[0].querySelectorAll(".ft-th").forEach((o) => {
          if (o !== th) o.removeAttribute("data-dir");
        });
        if (state === 0) {
          th.removeAttribute("data-dir");
          rows.sort((a, b) => a.dataset.ftOrder - b.dataset.ftOrder);
        } else {
          th.dataset.dir = state === 1 ? "desc" : "asc";
          const sign = state === 1 ? -1 : 1;
          rows.sort((a, b) => {
            const av = vals[c] ? vals[c][a.dataset.ftOrder] : null;
            const bv = vals[c] ? vals[c][b.dataset.ftOrder] : null;
            if (av !== null && bv !== null && av !== undefined && bv !== undefined)
              return sign * (av - bv);
            return sign * a.cells[c].textContent.localeCompare(
              b.cells[c].textContent, "zh");
          });
        }
        rows.forEach((r) => body.appendChild(r));
      };
      th.onclick = (e) => {
        if (th.dataset.def && e.altKey) {
          const row = document.getElementById(th.dataset.def);
          if (row) {
            row.scrollIntoView({block: "center", behavior: "smooth"});
            row.classList.add("ft-flash");
            setTimeout(() => row.classList.remove("ft-flash"), 1600);
          }
          return;
        }
        go();
      };
      th.onkeydown = (e) => { if (e.key === "Enter" || e.key === " ") { e.preventDefault(); go(); } };
    });

    if (rows.length < 6 || !labelCols.length) return;

    // facet chips, one group per label column
    const bar = document.createElement("div");
    bar.className = "ft-bar-row";
    const active = new Map();          // col -> Set(token)

    const apply = () => {
      let shown = 0;
      rows.forEach((r) => {
        const ok = [...active.entries()].every(([c, set]) => {
          if (!set.size) return true;
          const toks = r.cells[c].textContent.trim().split(SPLIT);
          return toks.some((t) => set.has(t));
        });
        r.style.display = ok ? "" : "none";
        if (ok) shown++;
      });
      count.textContent = `${shown} / ${rows.length} 行`;
    };

    labelCols.forEach((c) => {
      const freq = new Map();
      rows.forEach((r) => {
        new Set(r.cells[c].textContent.trim().split(SPLIT).filter(Boolean))
          .forEach((t) => freq.set(t, (freq.get(t) || 0) + 1));
      });
      const toks = [...freq.entries()]
        .filter(([t, n]) => n > 1 && n < rows.length && t.length < 34)
        .sort((a, b) => b[1] - a[1]).map(([t]) => t);
      if (toks.length < 2) return;
      active.set(c, new Set());
      const g = document.createElement("span");
      g.className = "ft-group";
      g.innerHTML = `<em>${head[c] || "标签"}</em>`;
      toks.forEach((t) => {
        const b = document.createElement("button");
        b.type = "button";
        b.textContent = t;
        b.onclick = () => {
          const set = active.get(c);
          set.has(t) ? set.delete(t) : set.add(t);
          b.setAttribute("aria-pressed", set.has(t));
          apply();
        };
        b.setAttribute("aria-pressed", "false");
        g.appendChild(b);
      });
      bar.appendChild(g);
    });

    // group: pull rows sharing a setting together by stripping trailing digits
    const grp = document.createElement("button");
    grp.type = "button";
    grp.className = "ft-act";
    grp.textContent = "按设置分组";
    let grouped = false;
    grp.onclick = () => {
      grouped = !grouped;
      grp.setAttribute("aria-pressed", grouped);
      if (grouped) {
        const key = (r) => labelCols
          .map((c) => r.cells[c].textContent.replace(/\d+/g, "").trim()).join("|");
        rows.sort((a, b) => key(a).localeCompare(key(b), "zh")
          || a.dataset.ftOrder - b.dataset.ftOrder);
      } else {
        rows.sort((a, b) => a.dataset.ftOrder - b.dataset.ftOrder);
      }
      rows.forEach((r) => body.appendChild(r));
    };

    const clear = document.createElement("button");
    clear.type = "button";
    clear.className = "ft-act";
    clear.textContent = "清除筛选";
    clear.onclick = () => {
      active.forEach((s) => s.clear());
      bar.querySelectorAll("[aria-pressed]").forEach(
        (b) => b.setAttribute("aria-pressed", "false"));
      grouped = false;
      grp.setAttribute("aria-pressed", "false");
      rows.sort((a, b) => a.dataset.ftOrder - b.dataset.ftOrder);
      rows.forEach((r) => body.appendChild(r));
      apply();
    };

    const count = document.createElement("span");
    count.className = "ft-count";
    count.textContent = `${rows.length} / ${rows.length} 行`;
    bar.append(grp, clear, count);
    if (bar.querySelector(".ft-group")) table.parentNode.insertBefore(bar, table);
    apply();
  };

  const css = document.createElement("style");
  css.textContent = `
.ft-num{text-align:right;font-variant-numeric:tabular-nums;white-space:nowrap;}
.ft-num .ft-track{position:relative;display:inline-block;vertical-align:middle;
 width:78px;height:8px;margin-right:10px;border-radius:2px;
 background:var(--edge,#e0dfd9);opacity:.85;overflow:hidden;}
.ft-num .ft-track.ft-signed:after{content:"";position:absolute;left:50%;top:0;
 bottom:0;width:1px;background:var(--faint,#9aa0a6);opacity:.55;}
.ft-num .ft-fill{position:absolute;top:0;bottom:0;border-radius:2px;
 background:var(--eq,#1f7a6b);opacity:.75;}
.ft-num .ft-fill.ft-neg{background:var(--weak,#c4703a);}
.ft-num b{font-weight:400;}
@media(max-width:900px){.ft-num .ft-track{width:48px;margin-right:7px}}
@media(max-width:640px){.ft-num .ft-track{width:28px;margin-right:5px}}
.ft-th{cursor:pointer;user-select:none;position:relative;padding-right:14px!important;}
.ft-th-num{text-align:right!important;}
.ft-def{border-bottom:1px dotted currentColor;}
.ft-def:after{content:' ⓘ';opacity:.55;font-size:9px;}
tr.ft-flash{background:var(--eq,#1f7a6b);box-shadow:inset 0 0 0 999px rgba(31,122,107,.12);}
tr.ft-flash td{transition:background .3s}
.ft-th:hover{color:var(--ink);}
.ft-th[data-dir]:after{content:"\\25BC";position:absolute;right:2px;font-size:8px;
 opacity:.75;}
.ft-th[data-dir=asc]:after{content:"\\25B2";}
.ft-bar-row{display:flex;flex-wrap:wrap;gap:7px;align-items:center;
 margin:0 0 9px;font-size:12px;}
.ft-group{display:inline-flex;flex-wrap:wrap;gap:4px;align-items:center;
 padding:3px 7px;border:1px solid var(--edge);border-radius:6px;}
.ft-group em{font-style:normal;color:var(--dim);margin-right:3px;font-size:11px;}
.ft-bar-row button{font:400 12px/1 inherit;cursor:pointer;padding:4px 8px;
 border:1px solid var(--edge);border-radius:5px;background:var(--panel);
 color:var(--dim);}
.ft-bar-row button[aria-pressed=true]{background:var(--eq,#1f7a6b);
 border-color:transparent;color:var(--panel);}
.ft-act{font-weight:500!important;}
.ft-count{color:var(--faint,#9aa0a6);font-family:monospace;margin-left:auto;}
@media print{.ft-bar-row{display:none}.ft-num .ft-fill{opacity:1}}`;
  document.head.appendChild(css);
  document.querySelectorAll("table").forEach((t) => {
    try { if (t.tHead && t.tBodies[0]) build(t); } catch (e) { /* leave as-is */ }
  });
})();
